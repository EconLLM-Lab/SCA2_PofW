#!/usr/bin/env python3
"""Write the anonymized copy of the held-out preregistration for double-anonymized review.

The copy keeps the registered text line for line. Only the spans in REDACTIONS change (author names, the
repository name, a local path, an internal title label), and the header lists each one with the SHA-256
hashes of the source file and of the version at the registration tag. A token from FORBIDDEN that survives
the redactions stops the script.

Usage:  python anonymize_prereg.py [--out-dir DIR]     (writes PREREGISTRATION_anonymized.md and .pdf)
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent
REPO = PAPER.parent.parent
SOURCE = REPO / "paper_b/heldout/PREREGISTRATION.md"
TAG = "prereg-heldout-2026-10-14"

REDACTIONS: list[tuple[str, str]] = [
    ("# Paper B held-out screen: preregistration", "# Held-out screen: preregistration"),
    ("decided by him the same day", "decided by [Author A] the same day"),
    ("Augusto Gonzalez-Bonorino", "[Author A]"),
    ("(EconLLM-Lab/SCA2_PofW)", "([repository, anonymized for review])"),
    ("/Users/bonorinoa/.hermes/profiles/sca/cache/scratch/probe_v1/selection.csv",
     "[local working directory]/probe_v1/selection.csv"),
]
FORBIDDEN = ["augusto", "gonzalez", "bonorino", "capra", "biriukova", "kseniia", "monica", "econllm",
             "sca2_pofw", "/users/", ".hermes", "arizona", "claremont", "@"]
FORBIDDEN_WORDS = re.compile(r"(?i)(?<![a-z])asu(?![a-z])")
HEADER_END = "<!-- end of anonymization header -->"


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def tagged_text() -> str:
    rel = SOURCE.relative_to(REPO).as_posix()
    return subprocess.run(["git", "-C", str(REPO), "show", f"{TAG}:{rel}"], check=True,
                          capture_output=True, text=True).stdout


def anonymize(source: str) -> str:
    body = source
    for old, new in REDACTIONS:
        body = body.replace(old, new)
    low = body.lower()
    left = [t for t in FORBIDDEN if t in low] + FORBIDDEN_WORDS.findall(body)
    assert not left, f"identifying tokens survive: {left}"
    tag = tagged_text()
    assert source.startswith(tag), "the registered sections changed after the tag"
    head = [
        "<!-- Anonymized copy for double-anonymized review. Generated by misc/paper_b/tools/anonymize_prereg.py. -->",
        "",
        "**Anonymized copy of the registration.** Sections 1 to 10 are the text registered by the git tag",
        f"`{TAG}`; sections 11 and 12 are the dated amendments appended afterwards, and the file contains no",
        "other change since the tag. Only the spans listed here were replaced; every other line is unchanged.",
        "",
        f"- SHA-256 of the source file: `{sha256(source)}`",
        f"- SHA-256 of the file at the tag (sections 1 to 10): `{sha256(tag)}`",
        "- Replaced spans:",
    ]
    head += [f"  - `{new}`" for _, new in REDACTIONS]
    return "\n".join(head) + "\n\n" + HEADER_END + "\n\n" + body


def write_pdf(md: Path, pdf: Path) -> None:
    """Typeset the copy verbatim (monospace, long lines wrapped) so the registered text keeps its layout."""
    bs = chr(92)
    tex = "\n".join([
        f"{bs}documentclass[10pt]{{article}}",
        f"{bs}usepackage[margin=0.9in]{{geometry}}",
        f"{bs}usepackage{{fontspec}}",
        f"{bs}setmonofont{{Menlo}}[Scale=0.82]",
        f"{bs}usepackage{{fvextra}}",
        f"{bs}pagestyle{{plain}}",
        f"{bs}begin{{document}}",
        f"{bs}VerbatimInput[breaklines=true,breakanywhere=true,fontsize={bs}small]{{{md.name}}}",
        f"{bs}end{{document}}", ""])
    with tempfile.TemporaryDirectory() as d:
        dd = Path(d)
        (dd / md.name).write_text(md.read_text())
        (dd / "prereg.tex").write_text(tex)
        for _ in range(2):
            subprocess.run(["xelatex", "-interaction=nonstopmode", "-halt-on-error", "prereg.tex"], cwd=dd,
                           check=True, capture_output=True)
        pdf.write_bytes((dd / "prereg.pdf").read_bytes())


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", type=Path, default=PAPER / "submission")
    a = ap.parse_args(argv)
    a.out_dir.mkdir(parents=True, exist_ok=True)
    md = a.out_dir / "PREREGISTRATION_anonymized.md"
    md.write_text(anonymize(SOURCE.read_text()))
    write_pdf(md, md.with_suffix(".pdf"))
    print(f"wrote {md.relative_to(REPO)} and {md.with_suffix('.pdf').name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
