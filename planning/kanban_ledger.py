"""Write planning/KANBAN_LEDGER.md: every SCA2 card on the Hermes kanban boards, tagged by workstream.

The kanban database lives in ~/.hermes, outside this repo, so a fresh agent (or a coauthor) cannot see
it. This ledger puts the card list on disk. It is generated, never hand-edited: rerun it after an SCA2
card closes.

    python3 planning/kanban_ledger.py            # reads the board SQLite databases read-only

Cards that belong to other projects (Silicus TA, ProjectOS, editor setup) are left out by rule: a card
is SCA2 when it runs inside an SCA2 worktree, sits on the sca2-paper-b board, or names SCA2 work in its
title. Within SCA2, workbench cards (the independent Adapter-Brain-Vizualization stream) are kept apart
from Paper B cards, so their compute and results are never read as Paper B's.
"""
from __future__ import annotations

import os
import re
import sqlite3
from collections import Counter
from datetime import datetime
from pathlib import Path

OUT = Path(__file__).resolve().parent / "KANBAN_LEDGER.md"
BOARDS = ("sca2-paper-b", "default")
SCA2_TITLE = re.compile(r"(?i)\bsca2\b|paper b|workbench|capture@")
WORKBENCH = re.compile(r"(?i)workbench|mac cohort|device benchmark|nf4 instrument|phase-1 cohort|capture@"
                       r"|llama-3 (rope|tokenizer)|float32|stage 1 claims"
                       r"|(?:^|\s)(?:W2|W3b?|WB[12])(?:\b|-)")


def board_db(board: str) -> Path:
    """Return the live database for *board* without invoking the Hermes CLI."""
    env_board = os.environ.get("HERMES_KANBAN_BOARD")
    env_db = os.environ.get("HERMES_KANBAN_DB")
    if env_db and board == env_board:
        return Path(env_db).expanduser()
    root = Path.home() / ".hermes"
    if board == "default":
        return root / "kanban.db"
    return root / "kanban" / "boards" / board / "kanban.db"


def cards(board: str) -> list[dict]:
    path = board_db(board)
    if not path.is_file():
        raise FileNotFoundError(f"kanban board database not found: {path}")
    uri = f"file:{path.resolve()}?mode=ro"
    with sqlite3.connect(uri, uri=True) as conn:
        conn.row_factory = sqlite3.Row
        return [dict(row) for row in conn.execute("SELECT * FROM tasks")]


def stream(card: dict) -> str | None:
    path, title = card.get("workspace_path") or "", card.get("title") or ""
    in_sca2 = "SCA2_PofW" in path or SCA2_TITLE.search(title)
    if card["_board"] != "sca2-paper-b" and not in_sca2:
        return None
    if ".worktrees/adapter-brain-vizualization" in path or WORKBENCH.search(title):
        return "workbench"
    return "paper-b"


def day(ts) -> str:
    return datetime.fromtimestamp(ts).strftime("%Y-%m-%d") if ts else ""


def main() -> None:
    rows = []
    for b in BOARDS:
        for c in cards(b):
            c["_board"] = b
            s = stream(c)
            if s:
                rows.append((s, c))
    rows.sort(key=lambda r: (r[0], r[1].get("completed_at") or r[1].get("created_at") or 0))
    count = Counter((s, c["status"]) for s, c in rows)
    lines = [
        "# SCA2 kanban ledger",
        "",
        f"Generated by [`kanban_ledger.py`](kanban_ledger.py) on {datetime.now():%Y-%m-%d %H:%M} from boards "
        f"{', '.join(f'`{b}`' for b in BOARDS)}. Do not edit by hand; rerun the script after an SCA2 card closes.",
        "Other projects' cards are excluded by rule (see the script). Workbench cards are listed apart from Paper B.",
        "A card's result is the worker's report. The repo and the Hub are the evidence: see [STATUS.md](../STATUS.md).",
        "",
        "| Stream | Cards | By status |",
        "|---|---:|---|",
    ]
    for s in ("paper-b", "workbench"):
        n = sum(v for (ss, _), v in count.items() if ss == s)
        by = ", ".join(f"{st} {v}" for (ss, st), v in sorted(count.items()) if ss == s)
        lines.append(f"| {s} | {n} | {by} |")
    for s in ("paper-b", "workbench"):
        lines += ["", f"## {s}", "", "| Finished | Card | Board | Owner | Status | Title |", "|---|---|---|---|---|---|"]
        for ss, c in rows:
            if ss != s:
                continue
            title = (c.get("title") or "").replace("|", "/")
            lines.append(f"| {day(c.get('completed_at'))} | `{c['id']}` | {c['_board']} | {c.get('assignee') or ''} "
                         f"| {c['status']} | {title} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(rows)} SCA2 cards)")


if __name__ == "__main__":
    main()
